(function () {
  const titleEl = document.getElementById('cdTitle');
  if (!titleEl) return;

  const urlParams = new URLSearchParams(window.location.search);
  const courseId = urlParams.get('id');
  const data = courseDetailsData[courseId] || courseDetailsData.default;

  document.getElementById('cdBadge').textContent = data.type;
  titleEl.textContent = data.title;
  document.getElementById('cdSubtitle').textContent = data.subtitle;
  document.getElementById('cdHeroBg').style.backgroundImage =
    `linear-gradient(180deg, rgba(12,12,12,0.35), rgba(12,12,12,0.85)), url('${data.image}')`;
  document.getElementById('cdDescContent').innerHTML = data.description;
  document.title = data.title + ' — EduXperts';

  const pageUrl = `https://eduxperts.com.tr/course-details.html?id=${courseId || 'default'}`;
  const imageUrl = `https://eduxperts.com.tr/${data.image}`;
  const setMeta = (selector, attr, value) => {
    const el = document.querySelector(selector);
    if (el) el.setAttribute(attr, value);
  };
  setMeta('meta[name="description"]', 'content', data.subtitle);
  setMeta('link[rel="canonical"]', 'href', pageUrl);
  setMeta('meta[property="og:title"]', 'content', data.title + ' — EduXperts');
  setMeta('meta[property="og:description"]', 'content', data.subtitle);
  setMeta('meta[property="og:url"]', 'content', pageUrl);
  setMeta('meta[property="og:image"]', 'content', imageUrl);
  setMeta('meta[name="twitter:title"]', 'content', data.title + ' — EduXperts');
  setMeta('meta[name="twitter:description"]', 'content', data.subtitle);

  const outcomesList = document.getElementById('cdOutcomesList');
  data.outcomes.forEach(item => {
    const li = document.createElement('li');
    li.textContent = item;
    outcomesList.appendChild(li);
  });
  if (!data.outcomes.length) outcomesList.innerHTML = '<li>No specific outcomes listed yet.</li>';

  const progList = document.getElementById('cdProgrammeList');
  const progTabBtn = document.getElementById('cdProgTabBtn');
  if (data.programme && data.programme.length) {
    data.programme.forEach(item => {
      const li = document.createElement('li');
      li.textContent = item;
      progList.appendChild(li);
    });
  } else {
    progTabBtn.style.display = 'none';
  }

  const sidebar = document.getElementById('cdSidebar');
  if (data.logistics) {
    document.getElementById('cdDuration').textContent = data.logistics.duration;
    document.getElementById('cdCost').textContent = data.logistics.cost;
    document.getElementById('cdLang').textContent = data.logistics.language || 'English';
    document.getElementById('cdLoc').textContent = data.logistics.location;
  } else {
    sidebar.style.display = 'none';
  }

  // TABS
  document.querySelectorAll('.cd-tab-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      document.querySelectorAll('.cd-tab-btn').forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      document.querySelectorAll('.cd-tab-content').forEach(c => { c.style.display = 'none'; });
      document.querySelector(`[data-tab-content="${btn.dataset.tab}"]`).style.display = 'block';
    });
  });
})();
